// Food-log gold set: realistic logs and the reference macros for the food in them.
// How references were derived (independent of data/foods.ts):
// - Whole foods: USDA FoodData Central (public domain): SR Legacy (2018-04), FNDDS 2021-2023 survey foods
//   (2024-10-31), Foundation (2026-04-30). Cooked forms for meat, fish, grains, pasta and rice unless the log
//   says raw/dry; "oats"/"rolled oats" in cups = dry, "oatmeal" = cooked. Portion weights come from the USDA
//   portion table of the cited food (FNDDS for everyday sizes like "1 banana", SR for cup/tbsp/oz); drink
//   "oz" = fluid ounces; 1 oz = 28.35 g, 1 fl oz = 29.57 ml.
// - No amount given: a typical single serving (4 oz / 113 g cooked meat or fish, 1 cup cooked rice or
//   vegetables, a medium fruit, 1 slice bread, 1 oz nuts, 1 tbsp oil/honey, 1 cup milk, 2 eggs for "eggs",
//   a 170 g yogurt cup, FNDDS "Quantity not specified" otherwise). Each item's source says which.
// - Branded and restaurant: the brand's published US nutrition (URL in source). Homemade dishes: the
//   matching FNDDS mixed dish (description and FDC id in source) at the stated or typical portion.
// - Eggs with no cooking method: hard-boiled (no added fat), 50 g large egg.
// Rounding: item kcal to integers, macros to 0.1 g; ref = sum of the rounded items. kcal can exceed
// 4/4/9 x macros (alcohol, fiber, USDA's own energy factors).

export interface RefItem { name: string; grams?: number; kcal: number; protein: number; carbs: number; fat: number; source: string }
export interface FoodCase {
  id: string; // kebab-case, unique
  category: string; // here: simple, units, no_amount, branded, restaurant, homemade, mixed, messy, not_food (scout.ts has its own)
  input: string; // exactly what the user types
  date?: string; // logging date YYYY-MM-DD, default 2026-10-03 (a Saturday)
  ref: { kcal: number; protein: number; carbs: number; fat: number }; // totals for all food in the log (0s for not_food)
  items: RefItem[]; // the reference breakdown, one per food eaten
  workout?: string[]; // mixed: the exercises/workout the log also describes (the food parser must ignore them)
  tolerance?: 'tight' | 'normal' | 'loose'; // scout.ts: the scout's own kcal tolerance for this case
  note?: string; // why this case matters, if not obvious
}

